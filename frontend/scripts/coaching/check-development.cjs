const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const base = process.env.BASE_URL || "http://127.0.0.1:3010";
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_PATH || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe" });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.goto(base + "/lessons");
    await page.getByRole("link", { name: "能力档案", exact: true }).click();
    await page.getByLabel("学员昵称", { exact: true }).fill("小林");
    await page.getByRole("button", { name: "添加学员" }).click();
    await page.getByLabel("观察能力", { exact: true }).selectOption("defend");
    await page.getByLabel("观察依据 / 测试条件").fill("慢球10次，有6次增加高度");
    await page.getByRole("button", { name: "保存本次观察" }).click();
    await page.getByText("最近：", { exact: false }).waitFor();
    await page.reload();
    await page.getByText("最近：", { exact: false }).waitFor();
    await page.getByLabel("观察能力", { exact: true }).selectOption("defend");
    await page.getByLabel("本次表现").selectOption("2");
    await page.getByLabel("观察依据 / 测试条件").fill("同样慢球10次，有8次增加高度");
    await page.getByRole("button", { name: "保存本次观察" }).click();
    await page.getByText(/上次：正在形成 → 本次：基本做到/).waitFor();
    await page.getByLabel("学员昵称", { exact: true }).fill("小王");
    await page.getByRole("button", { name: "添加学员" }).click();
    assert.equal(await page.getByText("尚未观察", { exact: true }).count(), 12);
    const backup = await page.evaluate(() => localStorage.getItem("tennis-development-passports-v1"));
    await page.getByText("档案备份与恢复", { exact: true }).click();
    await page.getByLabel("导入档案备份").setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: Buffer.from(backup) });
    await page.getByRole("button", { name: "确认合并档案" }).click();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("tennis-development-passports-v1")).observations.length), 2);
    await page.getByLabel("导入档案备份").setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from('{"version":1,"players":[]}') });
    await page.getByText(/备份无效/).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    const out = path.resolve(__dirname, "../../../tmp/pdfs"); fs.mkdirSync(out, { recursive: true });
    await page.screenshot({ path: path.join(out, "passport-mobile.png"), fullPage: true });
    await page.evaluate(() => localStorage.setItem("tennis-development-passports-v1", "broken-original"));
    await page.reload();
    await page.getByText(/无法读取能力档案/).waitFor();
    assert.equal(await page.getByRole("button", { name: "添加学员" }).isDisabled(), true);
    assert.equal(await page.evaluate(() => localStorage.getItem("tennis-development-passports-v1")), "broken-original");
    await page.getByText("档案备份与恢复", { exact: true }).click();
    await page.getByLabel("导入档案备份").setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: Buffer.from(backup) });
    await page.getByRole("button", { name: "保留异常副本并恢复备份" }).click();
    assert.equal(await page.evaluate(() => localStorage.getItem("tennis-development-passports-v1-recovery")), "broken-original");
    assert.deepEqual(errors, []);
    console.log("PASS passport: navigation, separate players, persistence, reassessment, import deduplication, invalid import, corruption recovery and mobile layout.");
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
