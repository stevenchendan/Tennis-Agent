import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import { createRequire } from "node:module";
import { webcrypto } from "node:crypto";
import ts from "typescript";
const module = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync(new URL("../src/lib/match-plan.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module, exports: module.exports, require: createRequire(import.meta.url), crypto: webcrypto });
const { emptyPlan, starterPlan, parsePlan, encodePlan, decodePlan, readiness, readPlans, MAX_LINK_LENGTH } = module.exports;
const plan = starterPlan();
assert.ok(readiness(plan).includes("Player name"));
plan.player = "Alex 李";
plan.title = "Final · 半决赛";
assert.equal(readiness(plan).length, 0);
const code = encodePlan(plan);
const shared = decodePlan(code);
assert.equal(JSON.stringify(shared), JSON.stringify(parsePlan(plan)));
plan.priorities[0] = "Changed after sharing";
assert.notEqual(decodePlan(code).priorities[0], plan.priorities[0], "shared snapshots must not change with the original");
assert.equal(decodePlan(""), null);
assert.equal(decodePlan("invalid payload"), null);
assert.equal(decodePlan("x".repeat(MAX_LINK_LENGTH + 1)), null);
assert.equal(parsePlan({ ...plan, version: 2 }), null);
assert.equal(parsePlan({ ...plan, situations: null }), null);
assert.equal(parsePlan({ ...plan, attachments: ["javascript:alert(1)"] }), null);
assert.equal(parsePlan({ ...plan, attachments: ["all-court", "all-court"] }), null);
assert.equal(parsePlan({ ...plan, priorities: ["missing two"] }), null);
assert.equal(parsePlan({ ...plan, objective: "x".repeat(601) }), null);
assert.equal(parsePlan({ ...plan, date: "not-a-date" }), null);
assert.equal(parsePlan({ ...plan, evidence: "Proven fact" }), null);
assert.equal(parsePlan({ ...plan, hiddenPrivateNotes: "not shared" }).hiddenPrivateNotes, undefined);
assert.equal(readPlans(JSON.stringify([plan, { invalid: true }])).length, 1);
assert.throws(() => readPlans("{}"));
assert.throws(() => readPlans("broken-json"));
assert.notEqual(emptyPlan().id, emptyPlan().id);
assert.ok(readiness(emptyPlan()).length > 0);
console.log("Game-plan checks passed: validation, readiness, Unicode sharing, immutable snapshots, import filtering and malformed/oversized data.");
